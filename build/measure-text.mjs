// Measures the width of each Latin character in button text (Inter, medium weight, at the small,
// medium and large control font sizes) in Chromium, and writes the table Toolbar estimates button
// widths from without script: src/IzzyBlazor.Core/Core/_generated/TextWidths.g.cs.
//
// Run it again when the Inter package or the button font sizes change:
//   node build/measure-text.mjs --chromium <path to chrome>
// It needs playwright-core (not a dependency of the build): npm i --no-save playwright-core.
// The stylesheet is wwwroot/izzyblazor.css, so build the assets first.

import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lib = join(root, "src", "IzzyBlazor.Core");
const args = process.argv.slice(2);
const chromium = args.includes("--chromium") ? args[args.indexOf("--chromium") + 1] : undefined;

const { chromium: browserType } = await import("playwright-core");
const browser = await browserType.launch({ executablePath: chromium });
const page = await browser.newPage();

// Latin, Latin-1 and Latin Extended-A: what a button label in a Western language uses.
const codes = [];
for (let c = 0x20; c <= 0x7e; c++) codes.push(c);
for (let c = 0xa0; c <= 0x17f; c++) codes.push(c);

const css = pathToFileURL(join(lib, "wwwroot", "izzyblazor.css")).href;
// A file page, so it can read the stylesheet and fonts from disk.
const html = join(mkdtempSync(join(tmpdir(), "ib-measure-")), "measure.html");
writeFileSync(html, `<!doctype html><html><head><link rel="stylesheet" href="${css}"></head><body>
  <button class="ib-btn ib-btn-sm"><span class="ib-btn-label" id="sm"></span></button>
  <button class="ib-btn"><span class="ib-btn-label" id="md"></span></button>
  <button class="ib-btn ib-btn-lg"><span class="ib-btn-label" id="lg"></span></button>
</body></html>`);
await page.goto(pathToFileURL(html).href);
// Every character on the page first, so each subset of the font (by unicode-range) has loaded.
await page.evaluate(async (codes) => {
  for (const id of ["sm", "md", "lg"]) {
    const span = document.getElementById(id);
    span.style.whiteSpace = "pre";
    span.textContent = String.fromCharCode(...codes);
  }
  await document.fonts.ready;
}, codes);

const sizes = {};
for (const id of ["sm", "md", "lg"]) {
  sizes[id] = await page.evaluate(
    ({ id, codes }) => {
      const span = document.getElementById(id);
      if (!getComputedStyle(span).fontFamily.startsWith("Inter")) throw new Error("Inter isn't the button font.");
      // Each character 20 times, so the width is exact to a fraction of a pixel.
      return codes.map((c) => {
        span.textContent = String.fromCharCode(c).repeat(20);
        return Math.round((span.getBoundingClientRect().width / 20) * 100);
      });
    },
    { id, codes }
  );
}
await browser.close();

const row = (values) => values.map((v, i) => (i % 16 === 0 ? "\n        " : " ") + v + ",").join("");
const out = `// <auto-generated>
// Written by build/measure-text.mjs from Inter in Chromium. Don't edit by hand.
// </auto-generated>

namespace IzzyBlazor;

/// <summary>Inter's character widths in button text, in hundredths of a pixel at a 16px root.</summary>
internal static partial class TextWidths
{
    /// <summary>The characters measured: U+0020 to U+007E, then U+00A0 to U+017F.</summary>
    private const int AsciiCount = ${0x7e - 0x20 + 1};

    private static readonly ushort[] Small =
    [${row(sizes.sm)}
    ];

    private static readonly ushort[] Medium =
    [${row(sizes.md)}
    ];

    private static readonly ushort[] Large =
    [${row(sizes.lg)}
    ];
}
`;
const target = join(lib, "Core", "_generated", "TextWidths.g.cs");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out.replace(/[ ]+\n/g, "\n"));
console.log(`Wrote ${target}`);
